"""
Normalized historical OHLCV dataset (Phase 8).

PIPELINE: provider -> normalize_ccxt_row -> OHLCVDataset -> Parquet.
Strategies NEVER see providers -- they receive the same MarketEvent
representation as everywhere else, generated by the backtest engine.

CANONICAL FORM & HASHING
------------------------
A dataset's identity is its CONTENT: sha256 over newline-joined canonical
rows sorted by ts. Canonical row = fixed-point strings via the project's
Decimal policy. File bytes may vary across parquet writers; the hash does
not.

TIME CONTRACT: timestamps are UTC epoch MILLISECONDS; `timeframe` uses
ccxt notation ("1m","5m","1h","1d").
"""
import hashlib
import json
from pathlib import Path
from typing import Any, Dict, Iterable, List

from pydantic import BaseModel

from src.core.money import Decimal, dec_to_str, to_decimal


_TIMEFRAME_MINUTES = {
    "1m": 1, "3m": 3, "5m": 5, "15m": 15, "30m": 30,
    "1h": 60, "2h": 120, "4h": 240, "6h": 360, "12h": 720, "1d": 1440,
}


def timeframe_minutes(timeframe: str) -> int:
    if timeframe not in _TIMEFRAME_MINUTES:
        raise ValueError(f"unsupported timeframe {timeframe!r}; "
                         f"supported: {sorted(_TIMEFRAME_MINUTES)}")
    return _TIMEFRAME_MINUTES[timeframe]


def normalize_ccxt_row(row: Iterable[Any]) -> Dict[str, Any]:
    """
    ccxt OHLCV row [ts, open, high, low, close, volume] (wire floats)
    -> canonical dict with Decimal fields. The str() hop is THE single
    sanctioned float ingestion boundary (same rule as live marking).
    """
    ts, o, h, low, c, v = row
    return {
        "ts": int(ts),
        "open": to_decimal(str(o)),
        "high": to_decimal(str(h)),
        "low": to_decimal(str(low)),
        "close": to_decimal(str(c)),
        "volume": to_decimal(str(v)),
    }


class Bar(BaseModel):
    """One normalized OHLCV bar. Decimals per canonical money policy."""
    model_config = {"frozen": True}

    ts: int                      # UTC epoch ms of bar OPEN
    open: Decimal
    high: Decimal
    low: Decimal
    close: Decimal
    volume: Decimal

    def canonical_row(self) -> str:
        return "|".join([
            str(self.ts), dec_to_str(self.open), dec_to_str(self.high),
            dec_to_str(self.low), dec_to_str(self.close),
            dec_to_str(self.volume),
        ])


class OHLCVDataset:
    """
    Immutable, sorted, content-addressed series for ONE symbol/timeframe.
    Plain class (not pydantic) -- it is a container, not a contract.
    """

    def __init__(self, bars: List[Bar], symbol: str, timeframe: str):
        self.symbol = symbol
        self.timeframe = timeframe
        self.bars: List[Bar] = sorted(bars, key=lambda b: b.ts)  # canonical order

    # ------------------------- construction ------------------------------

    @classmethod
    def from_records(cls, records: List[Any], symbol: str, timeframe: str) -> "OHLCVDataset":
        bars = [Bar(**normalize_ccxt_row(r)) for r in records]
        return cls(bars=bars, symbol=symbol, timeframe=timeframe)

    # --------------------------- properties -------------------------------

    def __len__(self):
        return len(self.bars)

    def __iter__(self):
        return iter(self.bars)

    @property
    def start_ts(self) -> int:
        return self.bars[0].ts

    @property
    def end_ts(self) -> int:
        return self.bars[-1].ts

    def closes(self) -> List[float]:
        """Float view for statistical/indicator contexts (documented policy)."""
        return [float(b.close) for b in self.bars]

    def opens(self) -> List[float]:
        return [float(b.open) for b in self.bars]

    def slice_indices(self, start: int, stop: int) -> "OHLCVDataset":
        return OHLCVDataset(self.bars[start:stop], symbol=self.symbol,
                            timeframe=self.timeframe)

    # ------------------------ identity & storage ---------------------------

    def content_hash(self) -> str:
        h = hashlib.sha256()
        header = f"{self.symbol}|{self.timeframe}|{len(self.bars)}"
        h.update(header.encode("utf-8"))
        h.update(b"\n")
        for b in self.bars:                       # bars already sorted by ts
            h.update(b.canonical_row().encode("utf-8"))
            h.update(b"\n")
        return h.hexdigest()

    def to_parquet(self, path: str | Path) -> Path:
        import pandas as pd

        df = pd.DataFrame([{
            "ts": b.ts,
            "open": dec_to_str(b.open), "high": dec_to_str(b.high),
            "low": dec_to_str(b.low),   "close": dec_to_str(b.close),
            "volume": dec_to_str(b.volume),
        } for b in self.bars])
        meta = {"symbol": self.symbol, "timeframe": self.timeframe}
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        df.to_parquet(path.with_suffix(".parquet"), index=False)
        path.with_suffix(".meta.json").write_text(
            json.dumps(meta, sort_keys=True), encoding="utf-8")
        return path.with_suffix(".parquet")

    @classmethod
    def from_parquet(cls, path: str | Path) -> "OHLCVDataset":
        import pandas as pd

        path = Path(path)
        meta = json.loads(path.with_suffix(".meta.json").read_text(encoding="utf-8"))
        df = pd.read_parquet(path)
        bars = [Bar(
            ts=int(r.ts),
            open=to_decimal(str(r.open)), high=to_decimal(str(r.high)),
            low=to_decimal(str(r.low)),   close=to_decimal(str(r.close)),
            volume=to_decimal(str(r.volume)),
        ) for r in df.itertuples()]
        return cls(bars=bars, symbol=meta["symbol"], timeframe=meta["timeframe"])
